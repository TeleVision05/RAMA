#!/bin/bash
# Build ~/Desktop/RAMA.app — a double-clickable launcher for the game.
#
# A real .app bundle rather than a .command file, so it gets a Dock icon and does not
# open a Terminal window. It runs the project IN PLACE, so the app always launches
# whatever is in the working tree; there is no second copy to keep in sync.
#
#   tools/make_app.sh [destination]     # default: ~/Desktop
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-$HOME/Desktop}"
APP="$DEST/RAMA.app"

if [ ! -f "$ROOT/build/RAMA.icns" ]; then
  echo "building icon first..."
  python3 "$ROOT/tools/make_icon.py"
fi

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$ROOT/build/RAMA.icns" "$APP/Contents/Resources/RAMA.icns"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>               <string>RAMA</string>
    <key>CFBundleDisplayName</key>        <string>RAMA</string>
    <key>CFBundleIdentifier</key>         <string>com.rama.game</string>
    <key>CFBundleVersion</key>            <string>1.0</string>
    <key>CFBundleShortVersionString</key> <string>1.0</string>
    <key>CFBundlePackageType</key>        <string>APPL</string>
    <key>CFBundleExecutable</key>         <string>RAMA</string>
    <key>CFBundleIconFile</key>           <string>RAMA</string>
    <key>LSMinimumSystemVersion</key>     <string>11.0</string>
    <key>NSHighResolutionCapable</key>    <true/>
    <key>LSApplicationCategoryType</key>  <string>public.app-category.adventure-games</string>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/RAMA" <<LAUNCH
#!/bin/bash
# Generated by tools/make_app.sh — edit that, not this.
PROJECT="$ROOT"
GODOT="\$HOME/tools/Godot.app/Contents/MacOS/Godot"
LOG="\$HOME/Library/Logs/RAMA.log"
mkdir -p "\$(dirname "\$LOG")"

fail() {
  /usr/bin/osascript -e "display alert \"RAMA cannot start\" message \"\$1\" as critical" >/dev/null 2>&1
  exit 1
}

[ -x "\$GODOT" ] || fail "Godot 4 was not found at:\n\$GODOT\n\nInstall Godot 4.7 there, or re-run tools/make_app.sh after editing it."
[ -f "\$PROJECT/project.godot" ] || fail "The game project was not found at:\n\$PROJECT\n\nRe-run tools/make_app.sh from the project."

echo "=== RAMA launch \$(date) ===" >> "\$LOG"
cd "\$PROJECT" || fail "Could not open \$PROJECT"
exec "\$GODOT" --path "\$PROJECT" >> "\$LOG" 2>&1
LAUNCH

chmod +x "$APP/Contents/MacOS/RAMA"
touch "$APP"
LSREG=/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister
[ -x "$LSREG" ] && "$LSREG" -f "$APP" 2>/dev/null || true
echo "built $APP"
